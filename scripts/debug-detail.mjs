import { _electron as electron } from 'playwright-core';
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.'], cwd: process.cwd(), env });
const page = await app.firstWindow();
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
await page.waitForSelector('a[href*="/detail/"]', { timeout: 45000 });
const href = await page.locator('a[href*="/detail/"]').first().getAttribute('href');
console.log('first card href:', href);
await page.locator('a[href*="/detail/"]').first().click();
await page.waitForTimeout(6000);
const text = await page.locator('main').innerText();
console.log('--- detail text ---');
console.log(text.slice(0, 800));
console.log('--- logs ---');
console.log(logs.filter((l) => !/IMG|img/.test(l)).slice(0, 20).join('\n'));
await app.close();
